! ****** common varibales for equiliburium calculation *****

MODULE eqcomm

  PUBLIC eqcomm

CONTAINS
  
  USE eqcomm_parm
  IMPLICIT NONE

  REAL(rkind) RAXIS,ZAXIS,PSI0,PSIPA,PSITA,REDGE
  REAL(rkind) PVOL,RAAVE,BETAT,BETAP,QAXIS,QSURF
  REAL(rkind) TJ,PSIITB,IDCALV
  REAL(rkind) RRC,RIPX,RBRA
  REAL(rkind) RXPNT1,ZXPNT1,PSIXPNT1,RXPNT2,ZXPNT2,PSIXPNT2
  REAL(rkind) NXPOINT

  REAL(rkind),DIMENSION(:),ALLOCATABLE:: RG,ZG
  REAL(rkind),DIMENSION(:,:),ALLOCATABLE:: PSIRZ
  REAL(rkind),DIMENSION(:),ALLOCATABLE:: PSIPS,PPPS,TTPS
  REAL(rkind),DIMENSION(:),ALLOCATABLE:: DPPPS,TTDTTPS,QQPS,DTTPS
  REAL(rkind),DIMENSION(:),ALLOCATABLE:: TEPS,OMPS
  REAL(rkind),DIMENSION(:,:,:,:),ALLOCATABLE:: UPSIRZ
  REAL(rkind),DIMENSION(:,:),ALLOCATABLE:: HJTRZ
  REAL(rkind),DIMENSION(:,:,:,;),ALLOCATABLE:: UHJTRZ

  REAL(rkind),DIMENSION(:),ALLOCATABLE::  PSIPV,PSIPNV,RHOT
  REAL(rkind),DIMENSION(:),ALLOCATABLE::  PSITV,QPV,TTV,PSITV,FIPV
  REAL(rkind),DIMENSION(:,:),ALLOCATABLE::  UQPV,UPSITV,UTTV,VPV,UFIPV
  REAL(rkind),DIMENSION(:),ALLOCATABLE::  AVBB2,AVIR2,AVRR2

  REAL(rkind),DIMENSION(:),ALLOCATABLE:: RSU,ZSU
  REAL(rkind),DIMENSION(:),ALLOCATABLE:: RSW,ZSW

CONTAINS

  SUBROUTINE eqcomm_allocate
    USE eqcomm
    IMPLICIT NONE
    INTEGER:: ierr,id

    id=1
    ALLOCATE(RG(NRGMAX),ZG(NZGMAX),PSIRZ(NRGMAX,NZGMAX),STAT=ierr)
    IF(ierr.NE.0) GOTO 900
    id=2
    ALLOCATE(PSIPS(NPSMAX),PPPS(NPSMAX),TTPS(NPSMAX),STAT=ierr)
    IF(ierr.NE.0) GOTO 900
    id=3
    ALLOCATE(DPPPS(NPSMAX),TTDTTPS(NPSMAX),STAT=ierr)
    IF(ierr.NE.0) GOTO 900
    id=4
    ALLOCATE(QQPS(NPSMAX),DTTPS(NPSMAX),STAT=ierr)
    IF(ierr.NE.0) GOTO 900
    id=5
    ALLOCATE(TEPS(NPSMAX),OMPS(NPSMAX),STAT=ierr)
    IF(ierr.NE.0) GOTO 900
    id=6
    ALLOCATE(UPSIRZ(4,4,NRGMAX,NZGMAX),STAT=ierr)
    IF(ierr.NE.0) GOTO 900
    id=7
    ALLOCATE(HJTRZ(NRGMAX,NZGMAX),STAT=ierr)
    IF(ierr.NE.0) GOTO 900
    id=8
    ALLOCATE(UHJTRZ(4,4,NRGMAX,NZGMAX),STAT=ierr)
    IF(ierr.NE.0) GOTO 900

    id=9
    ALLOCATE(PSIPV(NRVMAX),PSIPNV(NRVMAX),RHOT(NRVMAX),STAT=ierr)
    IF(ierr.NE.0) GOTO 900
    id=10
    ALLOCATE(PSITV(NRVMAX),UPSITV(4,NRVMAX),STAT=ierr)
    IF(ierr.NE.0) GOTO 900
    id=11
    ALLOCATE(QPV(NRVMAX),UQPV(4,NRVMAX),STAT=ierr)
    IF(ierr.NE.0) GOTO 900
    id=12
    ALLOCATE(TTV(NRVMAX),UTTV(4,NRVMAX),STAT=ierr)
    IF(ierr.NE.0) GOTO 900
    id=13
    ALLOCATE(RSV(NRVMAX),VPV(NRVMAX),STAT=ierr)
    IF(ierr.NE.0) GOTO 900
    id=14
    ALLOCATE(AVBB2(NRVMAX),AVIR2(NRVMAX),AVRR2(NRVMAX),STAT=ierr)
    IF(ierr.NE.0) GOTO 900
    id=15
    ALLOCATE(FIPV(NRVMAX),UFIPV(4,NRVMAX),STAT=ierr)
    IF(ierr.NE.0) GOTO 900

    id=16
    ALLOCATE(RSU(NSUMAX+1),ZSU(NSUMAX+1),STAT=ierr)
    IF(ierr.NE.0) GOTO 900
    id=17
    ALLOCATE(RSW(NSUMAX+1),ZSW(NSUMAX+1),STAT=ierr)
    IF(ierr.NE.0) GOTO 900
    RETURN

900 CONTINUE
    WRITE(6,'(A,2I4)') &
         'XX eqcomm memory allocation error at id, ierr=',id,ierr
    CALL eqcomm_deallocate
    RETURN
  END SUBROUTINE eqcomm_allocate

  SUBROUTINE eqcomm_deallocate
    USE eqcomm
    IMPLICIT NONE

    IF(ALLOCATED(RG))      DEALLOCATE(RG)
    IF(ALLOCATED(ZG))      DEALLOCATE(ZG)
    IF(ALLOCATED(PSIRZ))   DEALLOCATE(PSIRZ)
    IF(ALLOCATED(PSIPS))   DEALLOCATE(PSIPS)
    IF(ALLOCATED(PPPS))    DEALLOCATE(PPPS)
    IF(ALLOCATED(TTPS))    DEALLOCATE(TTPS)
    IF(ALLOCATED(DPPPS))   DEALLOCATE(DPPPS)
    IF(ALLOCATED(TTDTTPS)) DEALLOCATE(TTDTTPS)
    IF(ALLOCATED(QQPS))    DEALLOCATE(QQPS)
    IF(ALLOCATED(DTTPS))   DEALLOCATE(DTTPS)
    IF(ALLOCATED(TEPS))    DEALLOCATE(TEPS)
    IF(ALLOCATED(OMPS))    DEALLOCATE(OMPS)
    IF(ALLOCATED(UPSIRZ))  DEALLOCATE(UPSIRZ)
    IF(ALLOCATED(HJTRZ))   DEALLOCATE(HJTRZ)
    IF(ALLOCATED(UHJTRZ))  DEALLOCATE(UHJTRZ)

    IF(ALLOCATED(PSIPV))   DEALLOCATE(PSIPV)
    IF(ALLOCATED(PSIPNV))  DEALLOCATE(PSIPNV)
    IF(ALLOCATED(RHOT))    DEALLOCATE(RHOT)
    IF(ALLOCATED(PSITV))   DEALLOCATE(PSITV)
    IF(ALLOCATED(UPSITV))  DEALLOCATE(UPSITV)
    IF(ALLOCATED(QPV))     DEALLOCATE(QPV)
    IF(ALLOCATED(UQPV))    DEALLOCATE(UQPV)
    IF(ALLOCATED(TTV))     DEALLOCATE(TTV)
    IF(ALLOCATED(UTTV))    DEALLOCATE(UTTV)
    IF(ALLOCATED(RSV))     DEALLOCATE(RSV)
    IF(ALLOCATED(VPV))     DEALLOCATE(VPV)
    IF(ALLOCATED(AVBB2))   DEALLOCATE(AVBB2)
    IF(ALLOCATED(AVIR2))   DEALLOCATE(AVIR2)
    IF(ALLOCATED(AVRR2))   DEALLOCATE(AVRR2)
    IF(ALLOCATED(FIPV))    DEALLOCATE(FIPV)
    IF(ALLOCATED(UFIPV))   DEALLOCATE(UFIPV)

    IF(ALLOCATED(RSU))     DEALLOCATE(RSU)
    IF(ALLOCATED(ZSU))     DEALLOCATE(ZSU)
    IF(ALLOCATED(RSW))     DEALLOCATE(RSW)
    IF(ALLOCATED(ZSW))     DEALLOCATE(ZSW)
    RETURN
  END SUBROUTINE eqcomm_deallocate

END MODULE eqcomm

